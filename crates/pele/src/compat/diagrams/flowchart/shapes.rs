pub(super) fn valid(name: &str) -> bool {
    SHAPES.iter().any(|(n, _)| *n == name)
}
pub(super) fn canonical(name: Option<&str>) -> &str {
    let Some(name) = name else { return "rect" };
    match name {
        "square" => "rect",
        "round" => "rounded",
        "ellipse" => "ellipse",
        "hexagon" => "hex",
        "diamond" => "diam",
        _ => SHAPES
            .iter()
            .find(|(n, _)| *n == name)
            .map_or("rect", |(_, v)| *v),
    }
}
