import { loadPele, PeleError } from '../../bindings/web/index.js';

const source = document.querySelector('#source');
const preview = document.querySelector('#preview');
const status = document.querySelector('#status');
const error = document.querySelector('#error');
const button = document.querySelector('#render');
let ready = false;
let trapped = false;
let engine;
const dark = { background: '#191b20', foreground: '#eceef5', surface: '#272b33', border: '#8f98ad', line: '#c4ccdf' };

function showError(value) {
  error.hidden = false;
  error.textContent = `${value.code}: ${value.message}${value.span ? ` (line ${value.span.line}, column ${value.span.column})` : ''}`;
  preview.replaceChildren();
  status.textContent = 'Diagram rejected; edit source and render again.';
}
async function draw() {
  if (!ready) return;
  if (trapped) { location.reload(); return; }
  try {
    const options = document.querySelector('#dark').checked ? { theme: dark } : {};
    const result = engine.render(source.value, options);
    error.hidden = true;
    // The only HTML inserted is SVG generated by the bounded Rust engine.
    preview.innerHTML = result.svg;
    const { width, height, geometry } = result;
    status.textContent = `Rust WASM v1 · ${geometry.nodes.length} nodes · ${geometry.edges.length} edges · ${width} × ${height}`;
  } catch (failure) {
    if (failure instanceof PeleError && failure.code !== 'internal') { showError(failure); return; }
    trapped = true;
    showError({ code: 'internal', message: 'WASM failed. Render again to reload the engine.' });
  }
}
async function selectExample() {
  const name = document.querySelector('#example').value;
  const response = await fetch(`../../fixtures/${name}.mmd`);
  if (!response.ok) throw new Error('Example could not load');
  source.value = await response.text();
  await draw();
}
document.querySelector('#form').addEventListener('submit', event => { event.preventDefault(); draw(); });
document.querySelector('#example').addEventListener('change', () => selectExample().catch(() => showError({ code: 'load', message: 'Example could not load' })));
document.querySelector('#dark').addEventListener('change', draw);
try {
  engine = await loadPele();
  ready = true; button.disabled = false;
  await selectExample();
} catch { showError({ code: 'load', message: 'Build WASM with scripts/build-wasm.sh, then serve this repository.' }); }
